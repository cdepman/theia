// Generates src/lib/visualization/outlines.ts: one simplified SVG path per country.
// Geometry: Natural Earth 1:50m (public domain), via the `world-atlas` package (ISC).
// Run with `npm run outlines`. The output is committed, so this only needs re-running
// when a country is added.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoAlbers, geoMercator, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
const countries = feature(topo, topo.objects.countries).features;

// ISO 3166-1 numeric ids, and a bounding box that keeps the part of each country worth drawing.
const SPECS = {
  US: { id: '840', bbox: [-126, 24, -66, 50], projection: () => geoAlbers().parallels([29.5, 45.5]).rotate([96, 0]) },
  GB: { id: '826', bbox: [-9, 49.5, 2.5, 59.5], projection: () => geoMercator() },
  JP: { id: '392', bbox: [128, 30, 146.5, 46], projection: () => geoMercator() },
};
const SIZE = 1000;

function clipPolygons(geometry, [w, s, e, n]) {
  const polys = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  const kept = polys.filter((poly) => {
    const ring = poly[0];
    const cx = ring.reduce((a, p) => a + p[0], 0) / ring.length;
    const cy = ring.reduce((a, p) => a + p[1], 0) / ring.length;
    return cx >= w && cx <= e && cy >= s && cy <= n;
  });
  return { type: 'MultiPolygon', coordinates: kept };
}

const out = {};
for (const [code, spec] of Object.entries(SPECS)) {
  const f = countries.find((c) => String(c.id) === spec.id);
  if (!f) throw new Error(`country ${code} not found`);
  const geometry = clipPolygons(f.geometry, spec.bbox);
  const projection = spec.projection().fitSize([SIZE, SIZE], { type: 'Feature', geometry });
  const path = geoPath(projection.precision(0.5));
  const [[x0, y0], [x1, y1]] = path.bounds({ type: 'Feature', geometry });
  const d = path({ type: 'Feature', geometry })
    .replace(/(-?\d+\.\d)\d+/g, '$1')
    .replace(/\.0(?=[^\d])/g, '');
  out[code] = { viewBox: [Math.floor(x0), Math.floor(y0), Math.ceil(x1 - x0), Math.ceil(y1 - y0)], d };
}

const header = `// Generated by scripts/build-outlines.mjs. Do not edit by hand.
// Geometry: Natural Earth 1:50m, public domain (naturalearthdata.com), via world-atlas.
import type { CountryCode } from '../../../shared/constants';

export interface Outline {
  /** min-x, min-y, width, height */
  viewBox: [number, number, number, number];
  d: string;
}

export const OUTLINES: Record<CountryCode, Outline> = `;
writeFileSync(new URL('../src/lib/visualization/outlines.ts', import.meta.url), `${header}${JSON.stringify(out, null, 2)};\n`);
for (const [k, v] of Object.entries(out)) console.log(k, v.viewBox, `${(v.d.length / 1024).toFixed(1)} KB`);
